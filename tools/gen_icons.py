#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# ============================================================
#  SpoolmanScale - gen_icons.py
#  Draws the few line icons the symbol font does not have
# ============================================================
#
# The Montserrat fonts carry LVGL's FontAwesome symbols and nothing else, and
# they are never regenerated (the line height would move every label). The
# icons the Info & Support screen and the web hand-off need - a cup, code
# brackets, a speech bubble, a cube, a book and a QR mark - are drawn here as
# 8 bit alpha images instead. The firmware tints them with img_recolor, so one
# image serves every palette.
#
# Each icon is a list of strokes on a 24 x 24 grid, the grid of the mock-ups.
# They are drawn eight times larger with round caps and joins and scaled down,
# which gives the soft edge a font glyph has.
#
#   python3 tools/gen_icons.py          writes src/ui/icons.cpp
#   python3 tools/gen_icons.py --check  fails when the file is out of date
#
# Needs Pillow.

import math
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "ui", "icons.cpp")
GRID = 24
SUPERSAMPLE = 8


def arc(cx, cy, rx, ry, a0, a1, steps=12):
    """Points along an ellipse from angle a0 to a1, degrees, y down."""
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / steps)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / steps)))
            for i in range(steps + 1)]


def rect(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]


# Strokes, each a polyline on the 24 grid.
CUP = [
    [(4, 14), (4, 8), (17, 8), (17, 14)],
    arc(10.5, 14, 6.5, 5, 0, 180),
    arc(17, 12.5, 2.5, 2.5, -90, 90),
    [(8, 3), (8, 5)],
    [(12, 3), (12, 5)],
]
CODE = [
    [(8, 7), (3, 12), (8, 17)],
    [(16, 7), (21, 12), (16, 17)],
]
CHAT = [
    [(4, 5), (20, 5), (20, 16), (9, 16), (4, 20), (4, 5)],
]
CUBE = [
    [(12, 3), (20, 7.5), (20, 16.5), (12, 21), (4, 16.5), (4, 7.5), (12, 3)],
    [(4, 7.5), (12, 12), (20, 7.5)],
    [(12, 12), (12, 21)],
]
BOOK = [
    [(2, 4), (8, 4)] + arc(8, 8, 4, 4, -90, 0) + [(12, 20), (10, 18), (2, 18), (2, 4)],
    [(22, 4), (16, 4)] + arc(16, 8, 4, 4, -90, -180) + [(12, 20), (14, 18), (22, 18), (22, 4)],
]
QR = [
    rect(3, 3, 10, 10),
    rect(14, 3, 21, 10),
    rect(3, 14, 10, 21),
    [(14, 14), (17, 14), (17, 17)],
    [(21, 14), (21, 21), (17, 21)],
    [(14, 21), (14, 18)],
]

# name, strokes, size in pixels, stroke width on the grid
ICONS = [
    ("ICON_CUP", CUP, 20, 2.4),
    ("ICON_CODE", CODE, 20, 2.4),
    ("ICON_CHAT", CHAT, 20, 2.4),
    ("ICON_CUBE", CUBE, 20, 2.4),
    ("ICON_BOOK", BOOK, 20, 2.4),
    ("ICON_QR", QR, 36, 2.0),
]


def render(strokes, size, width):
    big = size * SUPERSAMPLE
    scale = big / GRID
    img = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(img)
    w = width * scale
    r = w / 2
    for line in strokes:
        pts = [(x * scale, y * scale) for x, y in line]
        d.line(pts, fill=255, width=int(round(w)))
        for x, y in pts:
            d.ellipse((x - r, y - r, x + r, y + r), fill=255)
    return img.resize((size, size), Image.LANCZOS)


def emit():
    out = [
        "// Generated by tools/gen_icons.py - do not edit, run the script.",
        "// 8 bit alpha images, tinted with img_recolor where they are used.",
        '#include "icons.h"',
        "",
    ]
    for name, strokes, size, width in ICONS:
        px = render(strokes, size, width).tobytes()
        out.append("static const uint8_t %s_MAP[] = {" % name)
        for i in range(0, len(px), 16):
            out.append("  " + ", ".join("0x%02x" % b for b in px[i:i + 16]) + ",")
        out.append("};")
        out.append("const lv_img_dsc_t %s = {" % name)
        out.append("  {LV_IMG_CF_ALPHA_8BIT, 0, 0, %d, %d}, sizeof(%s_MAP), %s_MAP};" % (size, size, name, name))
        out.append("")
    return "\n".join(out)


def main():
    text = emit()
    if "--check" in sys.argv:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("src/ui/icons.cpp is out of date: run tools/gen_icons.py")
                return 1
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
